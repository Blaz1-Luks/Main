#include <stdio.h>
#include <locale.h>
int main(void)
{   
    setlocale(LC_ALL,"ru_RU.UTF-8");
    double тираж;
    double роялти=0;
    double часть1=0, часть2=0, часть3=0;

    printf("Введите тираж книги:");
    scanf("%lf", &тираж);

    if (тираж<=0){
        printf("Тираж должен быть больше нуля.\n");
    } else if (тираж<=10000){
        часть1=тираж*0.10;
        роялти=часть1;
    } else if (тираж<=50000){
        часть1=10000*0.10;
        часть2=(тираж-10000)*0.12;
        роялти = часть1 + часть2;
    } else{
        часть1=10000*0.10;
        часть2=(50000-10000)*0.12;
        часть3=(тираж-50000)*0.15;
        роялти=часть1+часть2+часть3;
    }

    printf("\nИсходный тираж: %.0f\n", тираж);
    printf("Разбивка по ступеням:\n");
    printf("До 10000 (10%%): %.2f\n", часть1);
    printf("От 10001 до 50000 (12%%): %.2f\n", часть2);
    printf("Свыше 50000 (15%%): %.2f\n", часть3);
    printf("Итого роялти: %.2f\n", роялти);

    return 0;
}
